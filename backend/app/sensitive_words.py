def check_sensitive(text: str) -> list[str]:
    """检测文本是否命中敏感词，返回命中的词列表（去重，保持出现顺序）。"""
    if not text:
        return []
    low = text.lower()
    hits: list[str] = []
    for words in SENSITIVE_WORDS.values():
        for w in words:
            if w in low and w not in hits:
                hits.append(w)
    return hits
